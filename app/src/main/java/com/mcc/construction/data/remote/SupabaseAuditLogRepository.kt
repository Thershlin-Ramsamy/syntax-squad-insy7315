package com.mcc.construction.data.remote

import com.mcc.construction.data.model.AuditLog
import com.mcc.construction.data.remote.dto.AuditLogRow
import com.mcc.construction.data.repository.AuditLogRepository
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map

class SupabaseAuditLogRepository(
    private val reads: BackendReadStore
) : AuditLogRepository {

    override fun observeAuditLog(): Flow<List<AuditLog>> {
        return reads.observeRows<AuditLogRow>(
            table = "audit_logs",
            primaryKey = "log_id"
        ).map { rows ->
            rows.map { row ->
                AuditLog(
                    logId = row.logId,
                    userId = row.userId,
                    action = row.action,
                    timestamp = BackendTime.timestamp(row.timestamp)
                )
            }.sortedWith(
                compareByDescending<AuditLog> {
                    it.timestamp
                }.thenByDescending {
                    it.logId
                }
            )
        }
    }

    override suspend fun record(
        userId: Int,
        action: String
    ): AuditLog {
        throw SecurityException(
            "Audit entries are generated by server operations. " +
                    "The Android client cannot write audit history."
        )
    }
}